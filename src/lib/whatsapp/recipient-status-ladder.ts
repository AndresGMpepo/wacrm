/**
 * Recipient delivery-status ladder shared by every channel that mirrors
 * outbound WhatsApp status webhooks onto `broadcast_recipients`
 * (native Meta Cloud API and Zernio-connected numbers both report the
 * same delivered/read/failed lifecycle Meta gives them).
 */

// pending → sent → delivered → read → replied. Webhook replays must
// never regress a recipient back down this ladder.
//
// `failed` is NOT on this ladder. It's a terminal side branch that is
// only valid from the early states (pending / sent) — once Meta has
// delivered or the user has read or replied, a later "failed" status
// event is a bug in the upstream pipeline or a spoof attempt and must
// be ignored.
const RECIPIENT_STATUS_LADDER = [
  'pending',
  'sent',
  'delivered',
  'read',
  'replied',
] as const

function ladderLevel(s: string): number {
  return (RECIPIENT_STATUS_LADDER as readonly string[]).indexOf(s)
}

/**
 * Can a recipient transition from `current` to `incoming`?
 *   - Along the ladder, only forward moves are allowed.
 *   - `failed` is accepted only from `pending` or `sent`; it's refused
 *     once the recipient has reached any of the success states.
 */
export function isValidStatusTransition(current: string, incoming: string): boolean {
  if (incoming === 'failed') {
    return current === 'pending' || current === 'sent'
  }
  if (current === 'failed') {
    return false // failed is terminal
  }
  const ci = ladderLevel(current)
  const ii = ladderLevel(incoming)
  if (ii < 0) return false // unknown incoming status
  if (ci < 0) return true // unknown current — accept anything on the ladder
  return ii > ci
}
